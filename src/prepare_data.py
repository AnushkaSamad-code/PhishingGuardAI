"""Inspect, clean, split, and document the actual Phase 1 datasets."""
from pathlib import Path
import sys
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from utils.preprocessing import clean_dataset, split_dataset

def prepare_one(file_name: str, content_column: str, label_column: str, prefix: str) -> dict:
    """Prepare one CSV and return source, cleaning, and split statistics."""
    path = ROOT / "data" / "raw" / file_name
    sample = pd.read_csv(path, nrows=0)
    frame = pd.read_csv(path)
    source_label_counts = {str(k): int(v) for k, v in frame[label_column].value_counts(dropna=False).items()}
    cleaned, cleaning = clean_dataset(frame, content_column, label_column)
    splits = split_dataset(cleaned, ROOT / "data" / "processed", prefix)
    return {"file": file_name, "source_columns": list(sample.columns), "source_label_counts": source_label_counts, "cleaning": cleaning,
            "class_counts": {str(k): int(v) for k, v in cleaned["label"].value_counts().sort_index().items()},
            "splits": splits}

def main() -> None:
    """Prepare URL and email corpora and write a reproducible dataset log."""
    records = [prepare_one("phishing_site_urls.csv", "URL", "Label", "url"),
               prepare_one("phishing_email.csv", "text_combined", "label", "text")]
    lines = ["# Dataset Preparation Log", "", "Generated by `python src/prepare_data.py` from the source CSV files.",
             "Label convention: `0` = legitimate/safe; `1` = phishing/bad.", ""]
    for r in records:
        c = r["cleaning"]
        lines += [f"## {r['file']}", "", f"- Original rows: {c['original_rows']:,}",
                  f"- Source columns: `{', '.join(r['source_columns'])}`",
                  f"- Original label values/counts: `{r['source_label_counts']}`",
                  f"- Null rows removed: {c['null_rows_removed']:,}",
                  f"- Whitespace-only rows removed: {c['whitespace_rows_removed']:,}",
                  f"- Exact duplicate rows removed: {c['duplicate_rows_removed']:,}",
                  f"- Final rows: {c['final_rows']:,}", f"- Final class counts (0=safe, 1=phishing): `{r['class_counts']}`", "",
                  "| Split | Rows | Safe (0) | Phishing (1) |", "|---|---:|---:|---:|"]
        for name, info in r["splits"].items():
            counts = info["class_counts"]
            lines.append(f"| {name} | {info['rows']:,} | {counts.get('0', 0):,} | {counts.get('1', 0):,} |")
        lines.append("")
    (ROOT / "documentation" / "dataset_log.md").write_text("\n".join(lines), encoding="utf-8")
    print("Prepared datasets:")
    for r in records:
        print(f"{r['file']}: {r['cleaning']['original_rows']} original -> {r['cleaning']['final_rows']} clean; splits={r['splits']}")

if __name__ == "__main__":
    main()
